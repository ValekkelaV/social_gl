-- ============================================================
-- СоцПоляна: перенумерация докладов в паре (секция, слот) одной функцией
-- ============================================================
-- Зачем функция, а не обычные insert/update из фронтенда.
--
-- Номер доклада — это его место в паре (секция, слот): ID доклада склеивается
-- как день-слот-секция-НОМЕР, и по этому номеру строится расписание. Значит,
-- вставка доклада в середину списка переставляет номера у всех, кто ниже, —
-- это не одна правка, а перенумерация всей ячейки.
--
-- Сделать её набором запросов нельзя по двум причинам.
--
-- 1. Уникальность проверяется построчно. `unique (section_slot_id, talk_number)`
--    в talk_assignments создан обычным (не отложенным) и проверяется сразу при
--    изменении строки. Поэтому `update ... set talk_number = talk_number + 1`
--    падает на первой же коллизии: строка 1 получает номер 2, который ещё
--    занят строкой 2. Классическая ловушка Postgres, и обходится она только
--    одним оператором (или двумя проходами в одной транзакции), а не порядком
--    запросов.
-- 2. Каждый запрос PostgREST — своя транзакция. Даже отложенный constraint
--    (deferrable initially deferred) не помог бы: он проверяется на коммите,
--    а коммитов будет столько же, сколько запросов. То есть наивное
--    «переставить PATCH-ами» ломается и по этой линии тоже.
--
-- Отсюда security invoker + plpgsql: всё внутри функции выполняется в одной
-- транзакции, а вызов из фронтенда — один HTTP-запрос.
--
-- ---------- Почему security invoker, а не definer ----------
--
-- Осознанно. definer выполнил бы запись от имени владельца и обошёл бы RLS —
-- то есть ровно та дыра, которую закрывает 30_views_security_invoker.sql, но
-- только уже на запись: любой вошедший смог бы двигать расписание. С invoker
-- права проверяются как обычно: члены комитета «Расписание секций» двигают,
-- остальные получают ошибку RLS на вставке. Ещё и поэтому функция не пытается
-- ничего «проверить самой» — за права отвечает политика, а не код.
--
-- ---------- Три прохода, а не один ----------
--
-- Первый проход уводит номера ячейки в минус. Без него третьему проходу не
-- хватило бы места: он переставляет строки по одной, и любая из них может
-- попасть на номер, который ещё держит соседка. В минусе положительные номера
-- свободны целиком, а минусы между собой уникальны (номера были уникальны).
-- Это тот же приём, что «сначала сдвинуть всё на +1000», но без магического
-- числа.
--
-- Перенос доклада между ячейками — это update, а не вставка: application_id в
-- talk_assignments уникален глобально (доклад живёт ровно в одной паре), и
-- `on conflict (application_id) do update` закрывает обе ветки одним запросом —
-- и «доклад уже здесь, поменять номер», и «доклад пришёл из другой ячейки».
-- created_at при этом сохраняется: доклад не создаётся заново, а переезжает.
--
-- Исходная ячейка переезд сам за собой не подчищает — фронтенд зовёт функцию
-- второй раз с её новым составом. Так у обеих ячеек одна и та же операция, а
-- не два разных пути правки.
--
-- ---------- Чего функция не делает ----------
--
-- Не создаёт section_day_numbers. Номер секции в дне — решение организатора, а
-- не следствие перетаскивания, и появляться он должен явно. Пропущенный номер
-- виден в talk_display_ids как display_id = NULL (см. 31), то есть молча не
-- теряется.
-- ============================================================

create or replace function reorder_talks(
  p_section_slot_id uuid,
  p_application_ids uuid[]  -- новый состав ячейки в нужном порядке
)
returns void
language plpgsql
security invoker
as $$
begin
  -- 1. Освободить положительные номера ячейки. Строка с номером n получает -n;
  --    уникальность внутри ячейки сохраняется, а положительный диапазон
  --    освобождается для шага 3.
  update talk_assignments
     set talk_number = -talk_number
   where section_slot_id = p_section_slot_id;

  -- 2. Снять то, чего нет в новом списке: доклад утащили в другую ячейку или
  --    обратно в пул. Пустой массив здесь снимает всё — это и есть «очистить
  --    ячейку». NULL в p_application_ids ничего не снимает (any(NULL) -> NULL).
  delete from talk_assignments ta
   where ta.section_slot_id = p_section_slot_id
     and not (ta.application_id = any (p_application_ids));

  -- 3. Расставить по местам. Позиция — индекс в массиве, начиная с 1: так
  --    номер доклада совпадает с его местом в списке и с последней цифрой ID.
  --    Повтор одного application_id в массиве Postgres отобьёт сам ошибкой
  --    «ON CONFLICT DO UPDATE command cannot affect row a second time».
  insert into talk_assignments (application_id, section_slot_id, talk_number)
  select ord.application_id, p_section_slot_id, ord.pos
    from unnest(p_application_ids) with ordinality as ord(application_id, pos)
  on conflict (application_id)
  do update set section_slot_id = excluded.section_slot_id,
                talk_number    = excluded.talk_number;
end;
$$;

comment on function reorder_talks(uuid, uuid[]) is
  'Полностью задаёт состав и порядок докладов в паре (секция, слот): лишние '
  'снимает, пришедшие из других ячеек переносит, номера проставляет 1..N по '
  'порядку массива. Существует потому, что unique (section_slot_id, talk_number) '
  'не отложенный и проверить перенумерацию можно только внутри одной транзакции. '
  'security invoker — права проверяет RLS, а не функция.';

-- Права: функция пишет в talk_assignments, поэтому доступна только тем, кому это
-- разрешила бы политика, — но EXECUTE всё равно надо выдать явно. По умолчанию
-- Postgres выдаёт EXECUTE роли PUBLIC, то есть и anon; отзываем и выдаём
-- вошедшим. Сама по себе выдача мало что решает (внутри RLS), но оставлять
-- anon право вызова незачем: он всё равно получит нулевой эффект или ошибку.
revoke execute on function reorder_talks(uuid, uuid[]) from public, anon;
grant  execute on function reorder_talks(uuid, uuid[]) to authenticated;

