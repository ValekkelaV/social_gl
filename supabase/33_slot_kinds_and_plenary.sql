-- ============================================================
-- СоцПоляна: типы слотов — пленарный и служебный, кроме докладного
-- ============================================================
-- Продолжение раздела «Секции и расписание» (этап 4). 07_scheduling.sql править
-- нельзя — он давно на проде, — поэтому всё новое здесь.
--
-- До этой миграции в схеме было ОДНО подразумеваемое устройство дня: слот —
-- это окно времени, в которое параллельно идут секции с докладами. Слова
-- «лекция», «круглый стол», «кофебрейк» встречались только в комментариях
-- (07_scheduling.sql:78 «модераторы, лекторы, участники круглых столов»), но
-- ни одной сущности под ними не было.
--
-- Как на самом деле (со слов владельца, 2026-09-18) — слотов ТРИ типа:
--
--   докладной (talk)    — то, что было: параллельные секции, доклады, ID
--                         «день-слот-секция-номер». Ничего не меняется.
--   пленарный (plenary) — лекция, круглый стол, семинар, обсуждение. Одно
--                         событие на слот. У него есть модератор; у круглого
--                         стола ещё и участники — эксперты, порядка десяти.
--   служебный (service) — регистрация, кофебрейк, открытие/закрытие. Ни
--                         модераторов, ни экспертов в принципе; всё содержание
--                         слота — его подпись («Кофебрейк») и время.
--
-- ---------- Почему тип — у слота, а не у «элемента программы» ----------
--
-- Отброшенный вариант: завести отдельную таблицу «элементы программы», а слот
-- оставить безтиповым окном времени, в которое элементы вешаются как попало.
-- Он выглядит общее и потому соблазнителен, но ломает ровно то, ради чего
-- раздел существует: докладная часть — это СЕТКА (секция × слот, вместимость
-- на пару, перенумерация), и её единица измерения — слот. Если слот перестанет
-- знать, докладной он или нет, то каждая вьюха и каждый запрос доски будут
-- выяснять это джойном, а «пустой докладной слот» и «служебный слот» станут
-- неразличимы. Тип слота — свойство самого слота, и это то же решение, что и
-- вместимость на пару в 31: единица учёта должна совпадать с единицей смысла.
--
-- ---------- Почему text + check, а не create type ... as enum ----------
--
-- В проекте перечисления есть (`application_status`, `generated_document_type`),
-- и по привычке здесь просится четвёртое. Но у этого конкретного перечисления
-- список форматов пленарной части прямо сейчас назван владельцем как открытый:
-- «возможно будут семинары или обсуждения». Добавление значения в enum — это
-- `alter type ... add value`, а он в PG15 не работает внутри транзакции вместе
-- с использованием этого значения. Плоские миграции накатываются файлом
-- целиком, то есть одной транзакцией, — и первая же миграция, которая добавит
-- формат и тут же заведёт такой слот, упадёт на ровном месте. text + check
-- расширяется обычным `alter table ... drop constraint / add constraint`.
-- Значения при этом английские, как и в остальных перечислениях проекта;
-- русские подписи живут в UI.
--
-- ---------- Почему тип слота становится неизменяемым, если в слоте пленарка ----------
--
-- См. комментарий к plenary_items ниже: это не побочный эффект, а то, ради
-- чего составной внешний ключ и написан.


-- ============================================================
-- ТИП СЛОТА
-- ============================================================
-- default 'talk' — не заглушка и не «чтобы not null прошёл»: все слоты, уже
-- лежащие на проде, действительно докладные, и это их настоящее значение.
-- Поэтому существующие строки не нужно переписывать отдельным update.

alter table time_slots
  add column kind text not null default 'talk';

alter table time_slots
  add constraint time_slots_kind_check
  check (kind in ('talk', 'plenary', 'service'));

-- Уникального ключа ради самого ключа здесь нет: (id) уже первичный. Этот
-- нужен как ЦЕЛЬ составного внешнего ключа из plenary_items (см. ниже) —
-- Postgres требует, чтобы FK ссылался на уникальный набор колонок, а не на
-- выражение. Индекс крошечный: слотов на всю конференцию единицы.
alter table time_slots
  add constraint time_slots_id_kind_key unique (id, kind);

comment on column time_slots.kind is
  'Тип слота: talk — докладная часть (параллельные секции с докладами), '
  'plenary — пленарное событие (лекция, круглый стол, семинар, обсуждение), '
  'service — служебное (регистрация, кофебрейк, открытие/закрытие). '
  'У пленарного слота есть ровно один элемент в plenary_items; у служебного '
  'содержания нет вообще — только подпись слота. Тип нельзя сменить, пока в '
  'слоте стоит пленарный элемент: сначала уберите элемент.';


-- ============================================================
-- ПЛЕНАРНЫЙ ЭЛЕМЕНТ
-- ============================================================
-- Один элемент на слот. Это решение владельца (2026-09-18): «пленарный» —
-- значит все вместе, поэтому два параллельных круглых стола — это два слота,
-- а не два элемента в одном. Отсюда `unique (slot_id)`, а не отдельная
-- таблица «колонок» вроде section_slots: сетка колонок существует для
-- докладной части, где она означает параллельные секции, и тащить её сюда
-- значило бы завести вторую сетку с другим смыслом.

create table plenary_items (
  id uuid primary key default gen_random_uuid(),

  slot_id uuid not null unique,

  -- Колонка-константа. Нужна ровно для одного: составной внешний ключ ниже
  -- ссылается на пару (id, kind) в time_slots, и эта пара обязана совпасть.
  -- Значит, привязать элемент можно ТОЛЬКО к слоту с kind = 'plenary' —
  -- лекция физически не может оказаться в докладном слоте или в кофебрейке.
  --
  -- Отброшенная альтернатива — триггер before insert, который проверяет тип
  -- слота и raise'ит. Триггер делает то же самое, но: (а) он не виден в \d,
  -- то есть следующий читатель схемы не узнает об инварианте, пока не
  -- наткнётся на ошибку; (б) его надо не забыть повесить и на update, иначе
  -- элемент можно перенести в чужой слот; (в) он не защищает от смены типа
  -- самого слота — а ключ защищает: `update time_slots set kind='service'`
  -- на слоте с лекцией упадёт с 23503, и это правильно, иначе лекция осталась
  -- бы висеть в служебном слоте. Цена — генерируемая колонка, существующая
  -- только ради ограничения, и это ровно та ловушка, которую надо объяснить:
  -- без этого абзаца `update or delete on table "time_slots" violates foreign
  -- key constraint` на смене типа выглядит случайной ошибкой.
  slot_kind text not null generated always as ('plenary') stored,

  format text not null,  -- lecture / round_table / seminar / discussion
  title text not null,   -- название для программы и доски
  description text,      -- аннотация; в UI необязательна

  -- Модератор — ровно один из двух источников, и оба источника настоящие:
  -- лекцию ведёт кто-то из оргкомитета (people), у круглого стола модератор —
  -- приглашённый эксперт (external_experts). Владелец выбрал «оба на выбор»,
  -- а не правило «лекция → организатор, круглый стол → эксперт», именно
  -- потому, что это привычка текущего сезона, а не закон природы: если через
  -- год лекцию захочет вести приглашённый, переделывать схему не придётся.
  --
  -- on delete set null, а НЕ cascade, и это расхождение с
  -- section_slot_moderators (там cascade) — намеренное: удаление эксперта там
  -- снимает одно назначение, здесь же каскад снёс бы ВСЮ лекцию или весь
  -- круглый стол вместе с участниками. Модератора потерять неприятно, лекцию
  -- из программы — сильно хуже.
  --
  -- Имена ключей заданы явно, а не отданы на автогенерацию (`_fkey`), и это не
  -- косметика. PostgREST различает вложенные объекты по имени ограничения:
  -- участники круглого стола сделали plenary_items и external_experts
  -- связанными ДВУМЯ путями сразу — напрямую (moderator_expert_id) и через
  -- plenary_participants, — и на запрос вида `external_experts(full_name)`
  -- он отвечает PGRST201 «could not embed because more than one relationship
  -- was found». Указать в запросе `!plenary_items_moderator_expert_fk` можно
  -- только если ключ так называется; имя, придуманное Postgres'ом, придётся
  -- подсматривать в \d, а оно изменится при пересоздании таблицы.
  moderator_person_id uuid,
  moderator_expert_id uuid,

  created_at timestamptz not null default now(),

  constraint plenary_items_moderator_person_fk
    foreign key (moderator_person_id) references people(id) on delete set null,
  constraint plenary_items_moderator_expert_fk
    foreign key (moderator_expert_id) references external_experts(id) on delete set null,

  constraint plenary_items_format_check
    check (format in ('lecture', 'round_table', 'seminar', 'discussion')),

  -- Не больше одного, а НЕ «ровно один» — и это не мягкость, а вынужденность.
  -- Написать здесь `= 1` очень хочется (у элемента же есть модератор), но
  -- тогда `on delete set null` выше перестаёт работать: при удалении эксперта
  -- Postgres сначала обнуляет поле, потом проверяет ограничения, и удаление
  -- падает на 23514. То есть удалить эксперта стало бы НЕВОЗМОЖНО, пока он
  -- хоть где-то модератор, — при том что constraint писался ради порядка, а
  -- не ради запрета на увольнение. С `<= 1` эксперт удаляется, а элемент
  -- остаётся без модератора, что и обещает комментарий к колонке.
  --
  -- Второе следствие того же выбора: элемент заводится раньше, чем выбран
  -- модератор (сначала «Круглый стол про X», потом «ведущий — имя»). «Ровно
  -- один» запретил бы сохранить такую заготовку. Правило «у элемента должен
  -- быть модератор» остаётся, но живёт в UI, где оно и проверяется по-русски,
  -- а не в 23514 без объяснений.
  constraint plenary_items_moderator_count_check
    check (num_nonnulls(moderator_person_id, moderator_expert_id) <= 1),

  constraint plenary_items_slot_fk
    foreign key (slot_id, slot_kind) references time_slots(id, kind) on delete cascade
);

create index idx_plenary_items_slot on plenary_items(slot_id);

comment on table plenary_items is
  'Пленарная часть: одно событие на пленарный слот — лекция, круглый стол, '
  'семинар или обсуждение. Привязка к слоту возможна только если у слота '
  'kind = ''plenary''; это обеспечивает составной внешний ключ, а не UI.';
comment on column plenary_items.format is
  'lecture — лекция, round_table — круглый стол, seminar — семинар, '
  'discussion — обсуждение. Список открытый: добавляется правкой '
  'constraint''а plenary_items_format_check, а не новым типом и не миграцией '
  'данных.';
comment on column plenary_items.moderator_person_id is
  'Модератор из оргкомитета (people). Одновременно с moderator_expert_id '
  'заполнено быть не может (см. plenary_items_moderator_count_check); '
  'оба пустых допустимы — модератор ещё не выбран.';
comment on column plenary_items.moderator_expert_id is
  'Модератор — приглашённый эксперт (external_experts). Удаление эксперта '
  'обнуляет поле, но НЕ удаляет элемент: потерять модератора неприятно, '
  'потерять лекцию из программы — хуже.';


-- ============================================================
-- УЧАСТНИКИ КРУГЛОГО СТОЛА
-- ============================================================
-- Порядка десяти экспертов на круглый стол — то есть many-to-many, и одной
-- колонкой это не выражается.
--
-- Ограничения «участники бывают только у круглых столов» здесь НЕТ намеренно,
-- хотя сейчас это так. Список форматов открыт (владелец называет семинары и
-- обсуждения как возможные), и у семинара участники — вещь совершенно
-- нормальная; запрет в БД пришлось бы снимать новой миграцией ровно тогда,
-- когда он помешает. Это тот случай, когда инвариант мягкий: лишние строки
-- в этой таблице ничего не ломают, в отличие от лекции в докладном слоте
-- (см. составной ключ выше). Форма участников просто не показывается для
-- форматов, которым она не нужна.

create table plenary_participants (
  plenary_item_id uuid not null references plenary_items(id) on delete cascade,
  expert_id uuid not null references external_experts(id) on delete cascade,

  -- Порядок перечисления в программе. Не unique: пока список заполняют,
  -- два человека легко получают одинаковый номер, и падать из-за этого
  -- на ровном месте незачем — пересортировать можно потом.
  sort_order int not null default 0,

  primary key (plenary_item_id, expert_id)
);

create index idx_plenary_participants_expert on plenary_participants(expert_id);

comment on table plenary_participants is
  'Участники круглого стола (и любого другого пленарного формата, которому '
  'они понадобятся) — внешние эксперты. Один и тот же эксперт может быть '
  'участником нескольких элементов.';


-- ============================================================
-- ПРАВА
-- ============================================================
-- Тип слота правит тот же комитет, что и сами слоты, — новые политики для
-- time_slots не нужны: политика time_slots_write_schedule (08) накрывает
-- колонку kind, потому что она на таблицу, а не на список колонок.
--
-- Содержимое пленарной части — комитет «Модераторы/лекции/круглые столы»:
-- ровно тот же, что уже гейтит external_experts и section_slot_moderators
-- (08_scheduling_rls.sql:88-98). Читать может весь оргкомитет, как и везде.
--
-- Следствие, о котором надо знать: слот заводит «Расписание секций», а лекцию
-- в нём заполняет уже «Модераторы/лекции/круглые столы». Человек из первого
-- комитета увидит пленарный слот и не сможет его наполнить. Это не дефект —
-- это тот же раскол, что и с экспертами, — но UI обязан объяснить его, а не
-- показать форму, которая молча отдаёт 42501.

alter table plenary_items enable row level security;
alter table plenary_participants enable row level security;

create policy plenary_items_select_all on plenary_items for select to authenticated
  using (exists (select 1 from people where id = auth.uid()));
create policy plenary_items_write_moderators on plenary_items for all to authenticated
  using (is_moderators_committee_member(auth.uid()) or is_owner(auth.uid()))
  with check (is_moderators_committee_member(auth.uid()) or is_owner(auth.uid()));

create policy plenary_participants_select_all on plenary_participants for select to authenticated
  using (exists (select 1 from people where id = auth.uid()));
create policy plenary_participants_write_moderators on plenary_participants for all to authenticated
  using (is_moderators_committee_member(auth.uid()) or is_owner(auth.uid()))
  with check (is_moderators_committee_member(auth.uid()) or is_owner(auth.uid()));


-- ============================================================
-- ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ
-- ============================================================
-- Вьюх. Для доски достаточно обычных select'ов, а каждая новая вьюха — это
-- ещё одна, которую надо не забыть пометить security_invoker (см. 30, а
-- также абзац про потерю этой опции при пересоздании в шапке 31). Тому, чего
-- не существует, потерять настройку нельзя.
--
-- Изменений в talk_display_ids и slot_capacity_warnings — и не требуется:
-- обе ходят в докладную часть через section_slots, а у пленарного и
-- служебного слота строк в section_slots нет вообще. Пленарный слот не
-- попадёт в предупреждение о вместимости не потому, что это обработано, а
-- потому, что ему нечего туда принести.
