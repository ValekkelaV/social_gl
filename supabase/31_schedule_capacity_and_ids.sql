-- ============================================================
-- СоцПоляна: две вьюхи "Секций" врали при параллельных секциях
-- ============================================================
-- Найдено при написании раздела «Секции и расписание» (этап 4). Обе вьюхи
-- созданы ещё в 07_scheduling.sql, когда про конференцию было известно меньше;
-- 07 править нельзя (давно на проде), поэтому обе пересоздаются здесь.
--
-- Как на самом деле устроена конференция (со слов владельца, 2026-09-18):
-- два дня, в каждом по три слота для докладов, 10–12 секций, и секции идут
-- ПАРАЛЛЕЛЬНО в разных аудиториях: А, Б, В занимают все три слота первого дня
-- одновременно, Г — только второй слот, Д, Е, Ж — второй день.
--
-- Что из этого следовало для схемы — два дефекта.
--
-- ---------- Дефект 1: вместимость считалась на слот, а не на пару ----------
--
-- slot_capacity_warnings группировала по ss.slot_id, то есть складывала доклады
-- ВСЕХ секций слота. Пока секции в слоте шли по очереди, это совпадало с парой
-- (секция, слот) и вьюха была права. При параллельных секциях она складывает
-- то, что складывать нельзя: четыре доклада в А плюс четыре в Б — это восемь
-- по слоту, и вьюха кричит «переполнение» там, где в каждой секции ровно по
-- четыре, то есть норма. Норма вместимости 4–6 относится к ОДНОЙ секции в
-- одном слоте — к паре (секция, слот), строке section_slots.
--
-- Порог (> 6) при этом не меняется — это контракт вьюхи, он из ТЗ.
--
-- ---------- Дефект 2: доклад молча исчезал из talk_display_ids ----------
--
-- Вьюха делала inner join на section_day_numbers. section_day_numbers — это
-- «номер секции в рамках дня»: строка появляется, когда секции проставлен
-- номер. Пока номера нет, inner join выбрасывал доклад из вьюхи ЦЕЛИКОМ — без
-- ошибки, просто строка не возвращалась, и доклад оказывался без ID.
--
-- Меняем на left join: строка остаётся, а display_id становится NULL (в
-- Postgres конкатенация с NULL даёт NULL, а не мусор) — пропуск становится
-- видимым. Это ровно тот же класс тишины, что политика без select (28) и
-- мёртвая история ревизий в контент-плане: пустой результат неотличим от
-- «данных нет».
--
-- ---------- Почему drop + create, а не create or replace ----------
--
-- У slot_capacity_warnings меняется состав и порядок колонок, а Postgres
-- через `create or replace view` запрещает переименовывать колонки («cannot
-- change name of view column») — он сопоставляет их по позиции. Так что
-- пересоздание, и комментарии к вьюхам тоже надо проставить заново: drop их
-- уносит.
--
-- ---------- Почему security_invoker прямо здесь ----------
--
-- 30_views_security_invoker.sql уже включила эту опцию на обеих вьюхах — но по
-- имени. Пересозданная вьюха начинает с чистого листа, и без этой строки обе
-- снова стали бы читаться ролью anon в обход RLS: настройка из 30 потерялась
-- бы, причём молча, и ровно у тех двух вьюх, которые читает новый раздел.
-- Свойство задаётся в самом create, а не отдельным alter после — чтобы его
-- нельзя было потерять при следующем пересоздании.
--
-- ---------- Чего здесь намеренно нет ----------
--
-- Ограничения на однозначность компонентов ID. Формат «день-слот-секция-номер»
-- склеен без разделителей, поэтому при ≥10 секций в дне или ≥10 докладов в
-- паре ID начинают совпадать (1-1-1-11 и 1-1-11-1 дают одно и то же). Ограничение
-- `check (section_number < 10)` в БД было бы честнее, но оно блокирует ввод в
-- момент, когда остановить работу нельзя, — а порог этот не технический, а
-- организационный (10–12 секций на всю конференцию, но не на день). Вместо
-- этого UI показывает предупреждение, а запрос-ловушка
-- supabase/sql-checks/find_display_id_collisions.sql проверяет уже введённые
-- данные.
-- ============================================================


-- ---------- ВМЕСТИМОСТЬ ПАРЫ (СЕКЦИЯ, СЛОТ) ----------

drop view if exists slot_capacity_warnings;

create view slot_capacity_warnings with (security_invoker = true) as
select
  ss.id as section_slot_id,
  ss.section_id,
  ss.slot_id,
  ts.day_id,
  count(ta.id) as talks_count
from section_slots ss
join time_slots ts on ts.id = ss.slot_id
join talk_assignments ta on ta.section_slot_id = ss.id
group by ss.id, ss.section_id, ss.slot_id, ts.day_id
having count(ta.id) > 6;

comment on view slot_capacity_warnings is
  'Пары (секция, слот) с числом докладов > 6. Считается ИМЕННО на пару, а не на '
  'слот: секции идут параллельно в разных аудиториях, и сумма по слоту дала бы '
  'ложное предупреждение там, где в каждой секции по 4–6 докладов. Мягкое '
  'предупреждение для UI, не блокировка. Порог 6 — верхняя граница из контекста '
  '(«4–6 докладов на слот»); если нужен другой, менять здесь.';


-- ---------- ЧЕЛОВЕКОЧИТАЕМЫЙ ID ДОКЛАДА ----------

drop view if exists talk_display_ids;

create view talk_display_ids with (security_invoker = true) as
select
  ta.id as talk_assignment_id,
  ta.application_id,
  cd.sort_order as day_number,
  ts.sort_order as slot_number,
  sdn.section_number,     -- NULL, если секции ещё не проставлен номер в этом дне
  ta.talk_number,
  (
    cd.sort_order::text
    || ts.sort_order::text
    || sdn.section_number::text
    || ta.talk_number::text
  ) as display_id         -- NULL, если section_number NULL — см. шапку миграции
from talk_assignments ta
join section_slots ss on ss.id = ta.section_slot_id
join time_slots ts on ts.id = ss.slot_id
join conference_days cd on cd.id = ts.day_id
left join section_day_numbers sdn
  on sdn.section_id = ss.section_id and sdn.day_id = cd.id;

comment on view talk_display_ids is
  'Составной ID доклада (день-слот-секция-доклад) вычисляется на лету, не хранится '
  'полем — зависит от изменяемых sort_order/section_number. section_day_numbers '
  'присоединяется left join: при inner join доклад в секции без номера в этом дне '
  'пропадал из вьюхи целиком, а так display_id = NULL и пропуск виден. '
  'ВНИМАНИЕ: склейка без разделителей однозначна только пока каждый компонент — '
  'одна цифра; при >=10 секций в дне или >=10 докладов в паре ID совпадают. '
  'БД это не запрещает намеренно (см. шапку 31), проверка — '
  'supabase/sql-checks/find_display_id_collisions.sql';
