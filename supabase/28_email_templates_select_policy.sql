-- ============================================================
-- email_templates: вернуть политику на SELECT
-- ============================================================
-- Найдено при сверке прода с репозиторием 2026-09-18 — и найдено случайно:
-- проверял я обратное направление («нет ли на проде политик, которых нет в
-- файлах»), а расхождение оказалось встречным.
--
-- Что было. На проде у email_templates включён RLS, есть политики на INSERT,
-- UPDATE и DELETE (их создал 16_rls_fixer.sql), гранты у authenticated на
-- месте — а политики на SELECT нет. При этом 10_communications_rls.sql её
-- создаёт (email_templates_select_all), и ни один файл её не дропает. То есть
-- это расхождение прода с репозиторием, а не чьё-то решение.
--
-- Почему это опаснее, чем «нет доступа». RLS включён — значит при отсутствии
-- подходящей политики select возвращает НЕ ошибку, а ноль строк. Экран
-- шаблонов писем выглядел бы просто пустым: «шаблонов ещё не завели», а не
-- «права отобрали». Грант при этом на месте, поэтому и `permission denied` не
-- подскажет, где искать. Заметить это можно только целенаправленной проверкой
-- политик — чем оно и было найдено. До сих пор не проявлялось, потому что
-- таблица пустая (0 строк) и её не читает ни фронтенд, ни функции: раздел
-- «Документы» — заглушка.
--
-- Почему новая миграция, а не правка 10_communications_rls.sql. 10 применена к
-- проду, а применённые миграции не редактируют (см. CLAUDE.md): иначе состояние
-- прода перестаёт воспроизводиться накатом файлов, и следующий, кто развернёт
-- базу с нуля, получит не то, что на проде.
--
-- Почему политика, а не отключение RLS. RLS на этом блоке — осознанная модель
-- (см. docs/design/rls-model.md), и снять его ради одной таблицы значит остаться
-- без политик на insert/update/delete тоже. Гранты — тоже не альтернатива:
-- грант решает «может ли роль в принципе», политика — «какие строки»; работают
-- только вместе (та же ловушка разобрана в 24_revoke_extra_grants.sql).
--
-- Тело политики дословно повторяет 10_communications_rls.sql: «весь оргкомитет
-- читает шаблоны». Если шаблоны надо будет ограничить конкретным комитетом —
-- это отдельное решение и отдельная миграция, а не побочный эффект починки.

-- drop → create, а не create: у Postgres нет `create policy if not exists`
-- (в отличие от `create table`), поэтому идемпотентность делается только так.
-- Тот же приём в 16_rls_fixer.sql.

drop policy if exists email_templates_select_all on email_templates;

create policy email_templates_select_all
  on email_templates for select
  to authenticated
  using (exists (select 1 from people where id = auth.uid()));
