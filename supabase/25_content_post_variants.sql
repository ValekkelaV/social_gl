-- ============================================================
-- Контент-план: текст поста отдельно на каждую площадку
-- ============================================================
-- 03_content_plan.sql держал ОДИН body и ОДНУ platform на пост — по умолчанию
-- считалось, что пост уходит куда-то одно. По итогам обсуждения это не так:
-- один материал идёт и в Telegram, и в ВК, но текст в них РАЗНЫЙ, и разница не
-- косметическая:
--   * в Telegram ссылки форматируются разметкой, в ВК разметки нет — ссылку
--     приходится вставлять иначе и отдельно;
--   * в Telegram используется свой эмодзи-пак, а в ВК к тем же местам
--     подбираются альтернативы вручную.
-- Плюс расходятся даты: в тг вышло во вторник, в вк — в четверг.
--
-- Почему отдельная таблица, а не колонки body_tg / body_vk рядом с body:
--   1) к каждой колонке нужен свой набор дат (scheduled_at, published_at,
--      published_url) — это шесть колонок вместо одной строки;
--   2) третья площадка (Дзен, сайт, что угодно) превращается в правку схемы,
--      а не в обычную строку;
--   3) «что где уже вышло» перестаёт выражаться одним запросом.
-- Отброшен и вариант «два поста на один материал, по одному на площадку»:
-- тогда «банк постов» (фильтр idea/draft) показывает один материал дважды,
-- а статусы и ревизии у копий расходятся, и связать их обратно нечем —
-- ровно та связь, которую этот файл и заводит.
--
-- Что миграция НЕ делает:
--   * не трогает таблицу content_posts (кроме комментариев к колонкам) —
--     она уже накатана на прод, поля остаются как есть;
--   * не заводит ревизии текстов вариантов. Триггер log_content_post_revision
--     из 03_... продолжает писать историю по content_posts.body/title, и после
--     этой миграции он фактически логирует только смену названия. История
--     правок признана непринципиальной, поэтому расширять триггер на варианты
--     сейчас не стали — это отдельная миграция, если понадобится;
--   * не удаляет вытесненные колонки поста: удаление — потеря данных и
--     поломка совместимости ради аккуратности, а не необходимость.
--
-- Права на новую таблицу — отдельным файлом (26_...), как и для всех
-- остальных разделов.

-- ---------- ТЕКСТ И ПУБЛИКАЦИЯ НА КОНКРЕТНОЙ ПЛОЩАДКЕ ----------
create table content_post_variants (
  id uuid primary key default gen_random_uuid(),

  post_id uuid not null references content_posts(id) on delete cascade,
  platform content_platform not null,

  -- Текст под эту площадку. Пустая строка — нормальное начальное состояние:
  -- вариант заводится сразу при создании поста, чтобы «было куда писать»,
  -- а не появляется в момент, когда площадка наконец выбрана.
  body text not null default '',

  -- Отложка и факт публикации живут на площадке, а не на посте: они расходятся.
  scheduled_at timestamptz,   -- когда планируем выпустить именно здесь
  published_at timestamptz,   -- когда реально вышло
  published_url text,         -- ссылка на вышедший пост, чтобы из админки
                              -- было куда перейти и проверить

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- Один вариант на площадку. Именно unique, а не проверка в приложении:
  -- иначе два варианта на одну площадку не различить ни в коде, ни глазами —
  -- непонятно, какой из них «настоящий текст поста».
  unique (post_id, platform)

  -- Сознательно НЕТ ограничения вида "scheduled_at обязателен при ...": у
  -- варианта нет своего статуса, статус живёт на посте. Повторять проверку из
  -- 03_... здесь не от чего.
);

-- Отдельный индекс по post_id не нужен: unique (post_id, platform) создаёт
-- btree по этим колонкам, и выборка «все варианты одного поста» идёт по его
-- ведущей колонке.

-- updated_at ведём общим помощником set_updated_at (он определён в 05, и им же
-- пользуются 07 и 09). Своя копия, как в 03, здесь не нужна.
create trigger trg_content_post_variants_updated_at
  before update on content_post_variants
  for each row
  execute function set_updated_at();


-- ---------- КОММЕНТАРИИ ДЛЯ ТЕХ, КТО ОТКРЫВАЕТ ТАБЛИЦЫ ГЛАЗАМИ ----------
comment on table content_post_variants is
  'Текст поста и состояние публикации — отдельно на каждую площадку. '
  'content_posts — это материал целиком: тема и стадия работы (idea ... published). '
  'Вариант — то, что реально уходит в конкретную соцсеть: свой текст, своя дата, '
  'своя ссылка на публикацию.';

comment on column content_post_variants.body is
  'Текст для этой площадки. Отличается от текста других площадок не косметикой: '
  'в Telegram разметка ссылок и кастомный эмодзи-пак, в ВК ни того, ни другого. '
  'Пустая строка допустима — вариант заводится заранее, до того как текст написан.';

comment on column content_post_variants.published_url is
  'Ссылка на вышедший пост. NULL, пока не опубликовано. Может остаться NULL и '
  'после публикации (старый пост могли не сохранить) — поэтому published_at и '
  'published_url намеренно не связаны проверкой: заполняются независимо.';

-- Колонки поста, вытесненные вариантами. Не удаляем (см. шапку), но помечаем —
-- чтобы следующий читатель схемы не решил, что текст поста надо брать отсюда.
comment on column content_posts.body is
  'ВЫТЕСНЕНО content_post_variants.body (миграция 25). Текст теперь разный для '
  'разных площадок и лежит на вариантах. Историческое поле: триггер ревизий '
  'по-прежнему пишет историю именно по нему.';

comment on column content_posts.platform is
  'ВЫТЕСНЕНО content_post_variants.platform (миграция 25). Один пост уходит на '
  'обе площадки, поэтому одна колонка здесь реальность не выражает.';

comment on column content_posts.scheduled_at is
  'Дата ближайшей публикации по всем площадкам (минимум из '
  'content_post_variants.scheduled_at). Свои даты — на вариантах; здесь значение '
  'поддерживается потому, что check-ограничение таблицы требует его при '
  'status = ''scheduled'', и по нему же удобно фильтровать список.';
