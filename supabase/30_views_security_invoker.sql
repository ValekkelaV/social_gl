-- ============================================================
-- СоцПоляна: вьюхи обходили RLS — включаем security_invoker
-- ============================================================
-- Почему это понадобилось.
--
-- Все вьюхи схемы созданы владельцем схемы public (в Supabase это роль
-- postgres, у неё BYPASSRLS) и без опции security_invoker. В Postgres 15+ это
-- значит, что RLS базовых таблиц к вьюхе НЕ применяется: вьюха выполняется с
-- правами владельца, а владелец политики не проверяет.
--
-- Само по себе это было бы безобидно, если бы вьюхи были доступны только
-- оргкомитету. Но Supabase раздаёт дефолтные привилегии на каждый новый
-- объект в public ролям anon/authenticated/service_role — и вьюха попадает
-- под них так же, как таблица. В итоге anon (ключ лежит в бандле фронтенда и
-- публичен по определению) читал вьюхи напрямую, в обход RLS.
--
-- Проверено на локальной сборке, не рассуждением — при одной строке в
-- content_posts:
--     select count(*) from content_posts_bank  ->  1   (владелец, RLS обойдён)
--     select count(*) from content_posts       ->  0   (RLS работает)
--
-- Сильнее всего достаётся mailing_recipients: это контактные email всех
-- заявителей и тексты фидбека, то есть через публичный ключ наружу уходили
-- персональные данные. Остальные вьюхи безобиднее (номера докладов, черновики
-- постов, карта «тикет ↔ комитет»), но дыра у них одна и та же.
--
-- Что делаем: security_invoker = true — вьюха начинает выполняться с правами
-- того, кто её читает, и RLS базовых таблиц применяется как обычно. Для
-- вошедшего оргкомитета не меняется ничего: на всех базовых таблицах есть
-- политика select «весь оргкомитет». Для anon — ноль строк вместо данных.
--
-- Отброшенные альтернативы:
--   - отозвать select у anon на эти шесть вьюх. Работает ровно до следующей
--     вьюхи: дефолтные привилегии раздаются автоматически, и забыть про них
--     так же легко, как в этот раз. Плюс scripts/verify_schema.sh сам делает
--     `grant all on all tables in schema public to ... anon ...` при сборке с
--     нуля — то есть отзыв затирается первой же проверкой наката, и локальная
--     база снова перестаёт воспроизводить прод. security_invoker — свойство
--     самой вьюхи, оно переживает и то, и другое.
--   - отозвать usage на схему public у anon. Закрыло бы всё разом, но сломало
--     бы вход: LoginPage зовёт rpc("create_login_token") до аутентификации,
--     то есть под anon.
--   - политики на самих вьюхах. Вьюхе они не нужны вовсе, когда она честно
--     выполняется от имени читающего.
--
-- Ни одна политика и ни одна функция схемы на эти вьюхи не ссылается
-- (проверено поиском по supabase/), поэтому рекурсии в RLS не будет. Из
-- фронтенда читается только application_read_counts (ApplicationsPage) —
-- читается вошедшим пользователем, продолжает работать.
--
-- Отдельная миграция, а не правка 01/03/05/07/09: все они давно на проде.
--
-- Как проверить после наката (должно вернуть 0 у anon и данные у вошедшего):
--     set role anon; select count(*) from mailing_recipients; reset role;
-- ============================================================

alter view public.ticket_actionable_by    set (security_invoker = true);
alter view public.content_posts_bank      set (security_invoker = true);
alter view public.application_read_counts set (security_invoker = true);
alter view public.mailing_recipients      set (security_invoker = true);
alter view public.talk_display_ids        set (security_invoker = true);
alter view public.slot_capacity_warnings  set (security_invoker = true);
