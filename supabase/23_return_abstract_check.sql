-- ============================================================
-- Заявки: возврат ограничения "тезисы обязательны"
-- ============================================================
-- 05_applications.sql создавал ограничение на таблице заявок:
--
--   check (abstract_text is not null or abstract_file_url is not null)
--
-- Postgres назвал его applications_check. На проде его СНЯЛИ вручную через
-- SQL Editor (миграции, которая бы это делала, нет — расхождение видно в
-- supabase/_pulled/remote_schema_20260918.sql). Причина снятия неизвестна,
-- но косвенная улика есть: оба импортёра (import_applications.py и _v2.py)
-- содержат ровно эту проверку и помечают такие строки как
--   "Нет ни текста тезисов, ни файла — заявка не пройдёт check-constraint в БД"
-- то есть в реальных выгрузках формы заявки без тезисов встречались, и
-- ограничение, судя по всему, мешало импорту.
--
-- Тем не менее правило решено вернуть: форма (Yandex Forms) тезисы требует,
-- значит новые данные ему соответствуют, а без ограничения в базу попадает
-- мусор — заявки, которые читающему нечего открывать.
--
-- ПОЧЕМУ drop if exists перед add:
-- ограничение создаётся ещё и в 05_applications.sql, поэтому на накате с нуля
-- оно уже есть, и повторный add упал бы. Пара drop+add делает миграцию
-- идемпотентной и — главное — гарантирует, что после неё определение
-- ограничения ровно такое, как ниже, независимо от того, что было в базе.
-- На проде это возврат снятого, на чистой базе — пересоздание того же самого.
--
-- ПОЧЕМУ not valid + validate, а не просто add:
-- add constraint сразу валидирует все существующие строки и на большой таблице
-- держит блокировку на время проверки. not valid добавляет ограничение, не
-- проверяя старые строки (новые при этом уже проверяются), а validate выносит
-- проверку в отдельный шаг — видно, что именно упало.
--
-- ЧТО ДЕЛАТЬ, ЕСЛИ validate ПАДАЕТ:
-- это значит, что на проде есть заявки без тезисов, и их надо разобрать.
-- Найти их:
--   select id, title, contact_email, status, created_at
--   from applications
--   where abstract_text is null and abstract_file_url is null;
-- Дальше либо досылать тезисы этим заявкам, либо осознанно оставить их вне
-- ограничения (см. docs/design/decisions.md). Молча игнорировать не стоит:
-- после падения validate ограничение остаётся в состоянии not valid и старые
-- строки не покрывает, хотя новые уже отсекает.

alter table applications
  drop constraint if exists applications_check;

alter table applications
  add constraint applications_check
  check (abstract_text is not null or abstract_file_url is not null)
  not valid;

alter table applications
  validate constraint applications_check;

comment on constraint applications_check on applications is
  'У заявки обязан быть либо текст тезисов, либо ссылка на файл — хотя бы '
  'что-то одно. Правило пришло от формы (Yandex Forms тезисы требует), а не '
  'придумано в БД. Ограничение снималось на проде вручную и возвращено '
  'миграцией 23 — см. её шапку и docs/design/decisions.md.';
