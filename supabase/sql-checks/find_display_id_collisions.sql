-- Проверка ID докладов перед генерацией программы и расписания.
--
-- Формат ID (день-слот-секция-номер) склеен БЕЗ разделителей, поэтому однозначен
-- только пока каждый компонент — одна цифра. Если в дне больше девяти секций или
-- в паре (секция, слот) больше девяти докладов, разные доклады получают один и
-- тот же ID: «1-1-1-11» и «1-1-11-1» дают "11111". Ограничением в БД это не
-- закрыто намеренно (см. шапку 31) — ловим здесь.
--
-- Пустой результат — всё однозначно, можно генерировать документы.
-- Первая строка в выводе — совпавшие ID: сдвинуть номера секций в дне или номера
-- докладов в паре.
-- Вторая — доклады вообще без ID: секции не проставлен номер в этом дне
-- (section_day_numbers). В программу такой доклад попадёт без номера.
--
-- Один SELECT, а не два: supabase db query печатает только последний результат.

select
  t.проблема,
  t.что,
  t.сколько,
  t.подробности
from (
  select
    'совпавшие ID' as проблема,
    display_id as что,
    count(*) as сколько,
    string_agg(talk_assignment_id::text, ', ' order by talk_assignment_id) as подробности
  from talk_display_ids
  where display_id is not null
  group by display_id
  having count(*) > 1

  union all

  select
    'нет ID: секции не проставлен номер в дне' as проблема,
    application_id::text as что,
    1 as сколько,
    'день ' || day_number || ', слот ' || slot_number
      || ', доклад ' || talk_number as подробности
  from talk_display_ids
  where display_id is null
) t
order by t.проблема, t.что;
