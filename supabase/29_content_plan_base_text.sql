-- ============================================================
-- Контент-план: один базовый текст + текст карточек
-- ============================================================
-- По итогам обсуждения в чате 2026-09-18. Меняются две вещи, и обе — про то,
-- что текст бывает разный по природе, а не по площадке.
--
-- 1) Базовый текст возвращается на content_posts.body, а body варианта
--    становится НЕОБЯЗАТЕЛЬНЫМ переопределением: NULL = «как в посте».
--
--    Почему отменяем решение 25. 25 развела текст по площадкам, исходя из
--    того, что в тг есть разметка ссылок и свой эмодзи-пак, а в ВК нет. Это
--    правда — но набрать эту разницу в нашем редакторе всё равно нечем: у нас
--    обычная textarea, ни разметки, ни встраивания ссылки в слово в ней нет и
--    не планируется. Такие различия делаются в редакторе самой площадки при
--    публикации. Что реально остаётся — карточка-превью (в тг встроенная
--    ссылка её отключает, в ВК встроить нельзя, поэтому карточка будет всегда)
--    и подстановка эмодзи. Ради этого держать две полные копии текста — налог
--    с процентами: правят одну, вторая тихо расходится с тем, что вышло.
--
--    Почему NULL, а не пустая строка как признак «не переопределён». Пустая
--    строка уже занята буквальным смыслом «текста нет» (пост-картинка без
--    подписи), и совмещать в одном значении два смысла — ровно та ловушка,
--    из-за которой потом не отличить одно от другого. Та же причина, по
--    которой 27 сделала NULL у body ревизии означающим «на тот момент текста
--    не было», а не «пусто».
--
--    Побочный, но главный эффект: история ревизий снова работает.
--    log_content_post_revision() висит на content_posts и пишет снимок, когда
--    меняется content_posts.body или title. Пока тексты жили только в
--    вариантах, правка текста не порождала ревизию вообще: UI трогал в
--    content_posts только title/status/scheduled_at. Снимок появлялся при
--    создании и при переименовании — а при изменении текста нет. Теперь
--    базовый текст пишется в то самое поле, за которым триггер и следит, и
--    править в нём ничего не пришлось.
--
-- 2) Текст карточки — отдельная сущность на вложении, а не текст поста и не
--    текст площадки.
--
--    Почему на вложении. Текст карточки вшит в пиксели: одна картинка уходит
--    и в тг, и в ВК, поэтому расходиться по площадкам он не может в принципе.
--    Ось у него другая — «файл»: карусель из трёх картинок несёт три текста,
--    по одному на строку вложений. Хранить его в варианте значило бы написать
--    один и тот же текст дважды и однажды поправить только в одном месте.
--
--    Почему url стал nullable. Порядок работы обратный тому, как устроена
--    таблица: сначала пишется текст карточки, картинка приходит позже. С
--    not null такую строку было не завести, и текст жил бы в чате до лучших
--    времён. Теперь строка с url is null — это «карточка в работе»; файл
--    ляжет в ту же строку, когда появится.
--
--    Почему не caption. caption — подпись/alt для доступности: она остаётся
--    с файлом и читается скринридером. card_text — то, что генератор
--    «верстка + текст = картинка» подставляет в макет. Потребители разные, и
--    совместить их значит однажды переписать alt, чтобы поправить картинку.
--
--    Почему свободный текст, а не колонки под слоты макета (заголовок,
--    подпись, дата). Макетов ещё нет — раскладывать текст по слотам до того,
--    как макет появился, значит угадывать их названия и переделывать схему,
--    когда макет наконец нарисуют. Когда потребуются слоты — это будут
--    плейсхолдеры внутри одного поля, тем же приёмом, что в docx-шаблонах и
--    email_templates этапа 5.
--
-- Что НЕ версионируется: card_text. Триггер ревизий следит за content_posts и
-- про вложения не знает. Если история текстов карточек понадобится — это
-- отдельная правка триггера, а не побочный эффект этой миграции.
--
-- Данные. У существующих вариантов body = '' означает «текста нет» и
-- переносится в NULL, чтобы не читаться как «переопределение пустотой».
-- Запрос идемпотентен: повторный накат ничего не делает.

-- ------------------------------------------------------------
-- 1. Вариант площадки — переопределение, а не обязательный текст
-- ------------------------------------------------------------

alter table content_post_variants alter column body drop not null;

-- Default '' убирается вместе с not null: иначе новый вариант, заведённый без
-- текста, получал бы пустую строку — то самое значение, которое мы только что
-- объявили означающим «текста нет». Пусть будет NULL, то есть «не
-- переопределён».
alter table content_post_variants alter column body drop default;

update content_post_variants set body = null where body = '';

comment on column content_post_variants.body is
  'Текст для этой площадки. NULL — не переопределён, публикуется '
  'content_posts.body. Пустая строка — «текста нет» (пост-картинка без '
  'подписи), это другое значение. Заполняется только когда тексты '
  'действительно расходятся: например, из-за карточки-превью — в тг '
  'встроенная ссылка её отключает, в ВК встроить нельзя, поэтому карточка '
  'будет всегда. Разметка ссылок и эмодзи-пак сюда не относятся: в нашем '
  'редакторе их всё равно не набрать, они делаются в редакторе площадки.';

comment on table content_post_variants is
  'Состояние публикации — отдельно на каждую площадку: своя дата, своя ссылка '
  'на вышедший пост и НЕОБЯЗАТЕЛЬНОЕ переопределение текста. content_posts — '
  'материал целиком: тема, стадия работы (idea ... published) и базовый текст, '
  'который уходит на обе площадки, если вариант его не переопределяет.';

-- ------------------------------------------------------------
-- 2. Текст карточки — на вложении
-- ------------------------------------------------------------

alter table content_post_media alter column url drop not null;

alter table content_post_media add column card_text text;

comment on column content_post_media.url is
  'Ссылка на файл (Supabase Storage или внешняя, напр. Google Drive). NULL — '
  'файла ещё нет, есть только текст: строку заводят на этапе текста, картинка '
  'приходит позже и ложится в эту же строку.';

comment on column content_post_media.card_text is
  'Текст, вшиваемый в картинку этой карточки (генерация «верстка + текст»). '
  'Один на карточку, а не на площадку: картинка одна и уходит и в тг, и в ВК. '
  'Не путать с caption — тот про alt/доступность. Свободный текст с переносами '
  'строк; слоты макета, если понадобятся, — плейсхолдерами внутри этого поля.';

-- ------------------------------------------------------------
-- 3. Снятие пометки «вытеснено» с базового текста
-- ------------------------------------------------------------
-- 25 пометила content_posts.body как вытесненное, и на чистой базе эта пометка
-- ставится снова — здесь она перекрывается. Так и задумано: применённая
-- миграция не редактируется (см. CLAUDE.md), поэтому состояние прода
-- воспроизводится накатом 25 → 29, а не правкой 25.

comment on column content_posts.body is
  'Базовый текст поста — один на материал, уходит и в тг, и в ВК. Вариант '
  'площадки может его переопределить (content_post_variants.body), NULL в '
  'варианте означает «берётся отсюда». История правок этого поля пишется '
  'триггером в content_post_revisions.';
