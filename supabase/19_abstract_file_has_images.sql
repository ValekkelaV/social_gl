-- ============================================================
-- Заявки: флаг "в файле есть картинки"
-- ============================================================
-- При батч-извлечении текста из тезисов (docx/pdf) в abstract_text —
-- извлечение текста не переносит встроенные изображения (графики, схемы,
-- фото). Если файл их содержит, читающему нужно знать, что открыть сам
-- файл всё равно стоит — извлечённый текст неполон.

alter table applications
  add column abstract_file_has_images boolean;

comment on column applications.abstract_file_has_images is
  'true — в исходном файле тезисов (abstract_file_url) обнаружены встроенные '
  'изображения при батч-извлечении текста; abstract_text может быть неполным, '
  'стоит открыть оригинал по ссылке. null — извлечение ещё не запускалось '
  'для этой заявки (напр. abstract_text был введён вручную, не из файла). '
  'false — извлечение запускалось, изображений не найдено.';
