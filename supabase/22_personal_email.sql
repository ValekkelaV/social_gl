-- ============================================================
-- Докладчики: личный email
-- ============================================================
-- Новое поле формы: личный email докладчика. На него отправляется именной
-- сертификат об участии — в отличие от applications.contact_email, который
-- общий на всю заявку и указывается контактным лицом, а не обязательно
-- каждым соавтором лично.
--
-- Необязательное поле: часть докладчиков его не заполняет, и в старых
-- заявках его нет вовсе (не проставляется ретроактивно) — поэтому NULL
-- допустим и не является ошибкой данных.
--
-- Отдельная миграция, а не часть 20_speakers_city.sql: 20 накатывалась
-- на прод раньше (там уже есть city, но нет personal_email), и менять
-- уже применённый файл нельзя — иначе состояние БД разойдётся с
-- текстом миграции.

alter table speakers
  add column personal_email text;

comment on column speakers.personal_email is
  'Личный email докладчика (необязательное поле формы) — используется для '
  'отправки именного сертификата участия. Не путать с applications.contact_email, '
  'который общий на заявку и указывается контактным лицом, не обязательно '
  'каждым соавтором лично.';
