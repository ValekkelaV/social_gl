-- ============================================================
-- Докладчики: город
-- ============================================================
-- Раньше город (если вообще указывался) заносился внутрь свободного текста
-- university_raw (напр. "НИУ ВШЭ, Москва"). Выносим в отдельную колонку —
-- пригодится для статистики/фильтрации ("сколько участников не из Москвы"),
-- и не задваивает делимитер внутри university_raw.
 
alter table speakers
  add column city text;
 
comment on column speakers.city is
  'Город докладчика. Раньше иногда встречался как часть university_raw через '
  'запятую — начиная с новой формы это отдельное поле. Для старых записей '
  'может быть NULL (не проставлено ретроактивно).';
