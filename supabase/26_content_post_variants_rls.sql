-- ============================================================
-- RLS: варианты постов контент-плана (к 25_content_post_variants.sql)
-- ============================================================
-- Правила ровно те же, что у остального контент-плана
-- (04_content_plan_rls.sql): любой член оргкомитета — полный доступ, без
-- привязки к комитету. Проверки «человек есть в people» достаточно: она и
-- означает «входит в оргкомитет».
--
-- Почему не «доступ только СММ»: в 04 это решение уже принято для постов и
-- медиа, а вариант — та же сущность с другой стороны. Разные правила на пост и
-- на его текст дали бы худший из вариантов: строку в списке человек видит, а
-- при открытии карточки получает отказ. Права разошлись бы не по смыслу, а по
-- случайности разбиения на таблицы.
--
-- Гранты роли authenticated на новую таблицу выдаются автоматически — это
-- стандартные default privileges Supabase для схемы public (та же механика,
-- из-за которой ломается локальная проверка при потере pg_default_acl,
-- см. scripts/verify_schema.sh). Явных grant здесь не пишем, как и в 04.

alter table content_post_variants enable row level security;

create policy content_post_variants_all_org
  on content_post_variants for all
  to authenticated
  using (exists (select 1 from people where id = auth.uid()))
  with check (exists (select 1 from people where id = auth.uid()));
