-- ============================================================
-- Контент-план: ревизии постов не работали — чиним триггер и снимок
-- ============================================================
-- Все три бага найдены при проверке 25_content_post_variants.sql. До сих пор они
-- не всплывали по единственной причине: раздел «Контент-план» — заглушка на 8
-- строк, и в content_posts не было вставлено ни одной строки. Баги латентные,
-- не появившиеся от правок 25: они лежат в 03_... с самого начала.
--
-- Порядок разбора — по тому, как они проявляются: сначала «пост не создать»,
-- потом «в снимок не влезает отсутствующий текст», потом «правка вне приложения
-- отменяется».
--
-- Проверено, что прод в том же состоянии: функция log_content_post_revision в
-- supabase/_pulled/remote_schema_20260918.sql совпадает с 03_content_plan.sql
-- строка в строку. То есть чинится и прод, а не только репозиторий.
--
-- ----------
-- БАГ 1: пост нельзя было создать вообще.
--
-- Триггер trg_content_post_revision объявлен в 03_... как BEFORE INSERT OR UPDATE,
-- а его функция пишет строку в content_post_revisions со ссылкой на пост, которого
-- в момент срабатывания в таблице ещё нет (BEFORE INSERT — строка не вставлена).
-- Внешний ключ content_post_revisions_post_id_fkey объявлен без deferrable
-- (condeferrable = f), поэтому вставка внутрь функции падает:
--
--   ERROR:  insert or update on table "content_post_revisions" violates foreign key
--           constraint "content_post_revisions_post_id_fkey"
--   DETAIL: Key (post_id)=(...) is not present in table "content_posts".
--
-- То есть INSERT в content_posts не проходил НИКОГДА — ни с текстом, ни без.
-- UPDATE работал: там строка уже существует, и на неё можно сослаться.
--
-- Почему не сделали внешний ключ отложенным (deferrable initially deferred):
--   * это поменяло бы поведение всех вставок в content_post_revisions разом —
--     проверка уехала бы на commit, и ошибка всплывала бы не там, где возникла
--     (в чужой транзакции, в конце, а то и не у нас, а на стороне клиента);
--   * смысл не в порядке проверок, а в том, что BEFORE-триггер полез в таблицу,
--     сослаться на которую строка ещё не может. Отложенный FK замаскировал бы
--     это, а не исправил;
--   * FK пришлось бы пересоздавать — операция на проде более заметная, чем
--     замена триггера, при том же результате.
-- Почему не убрали ревизию на INSERT вовсе: первая ревизия — это запись «пост
-- появился», и без неё история начинается с середины: не видно, кто завёл пост
-- и с какого текста всё пошло.
--
-- Решение: разнести одну обязанность на два триггера по их природе.
--   * updated_at — это про изменение самой строки, ему место в BEFORE;
--     отдаём общему помощнику set_updated_at (он определён в 05 и уже
--     используется в 07 и 09 — так эта миграция не заводит третью копию);
--   * запись ревизии — это про уже существующую строку, ей место в AFTER,
--     где пост в таблице есть и FK выполняется.
--
-- ----------
-- БАГ 3: правка вне приложения не проходила вовсе.
--
-- На UPDATE триггер берёт автора из auth.uid(). В SQL Editor, в скрипте и в любом
-- серверном коде на service_role JWT нет, auth.uid() = null, и вставка ревизии
-- падает:
--
--   ERROR:  null value in column "edited_by" of relation "content_post_revisions"
--           violates not-null constraint
--
-- То есть падает не запись ревизии, а сама правка поста: триггер срывает UPDATE.
--
-- Это противоречит заявленной причине существования триггера. В
-- docs/design/schema-overview.md про него сказано: «Пишется триггером
-- log_content_post_revision(), а не приложением — чтобы правка через SQL Editor
-- тоже логировалась». Ровно этот сценарий сегодня невозможен: правка через
-- SQL Editor не логируется, а отменяется.
--
-- Почему не «подставлять автора поста (new.created_by), когда auth.uid() пуст»:
-- это записало бы в историю чужое имя. У журнала правок ровно одна задача —
-- говорить, кто и когда менял текст; ревизия с приписанным не тем человеком
-- хуже, чем ревизия с честным «автор неизвестен».
--
-- ----------
-- БАГ 2: снимок не мог хранить «текста ещё нет».
--
-- В 03_... объявлено несогласованно:
--
--   content_posts.body            text                 -- nullable
--   content_post_revisions.body   text not null
--
-- Ревизия — снимок состояния источника, и она обязана повторять источник как
-- есть, включая NULL. Пока пост всегда заводился вместе с текстом, расхождение
-- не проявлялось. После 25_... текст живёт на вариантах, и пост штатно создаётся
-- ДО того, как текст написан, — то есть NULL в снимке становится обычным делом.
--
-- Почему не «всегда писать body = '' из UI»: это спрятало бы ловушку в одном
-- клиенте, оставив её для всех остальных (SQL Editor, будущий импорт, скрипты).
-- Поле, которое не может хранить законное состояние источника, — это баг схемы,
-- а не обязанность приложения.
-- Почему не «сделать content_posts.body not null default ''»: пришлось бы
-- затирать существующие NULL пустой строкой, стерев разницу между «текста нет»
-- и «текст пустой». Плюс после 25 это поле вытеснено — нагружать его смыслом
-- тем более незачем.
--
-- 03_content_plan.sql не правим: она давно накатана на прод (см. CLAUDE.md).

-- ---------- БАГ 2: снимок повторяет источник, включая NULL ----------
alter table content_post_revisions alter column body drop not null;

comment on column content_post_revisions.body is
  'Текст поста на момент этой ревизии. NULL здесь — не «пусто», а «на тот момент '
  'текста не было»: пост могли завести до того, как текст написан (текст живёт '
  'на content_post_variants, см. миграцию 25). Значение копирует content_posts.body '
  'как есть, включая NULL.';

-- ---------- БАГ 3: ревизия без автора ----------
alter table content_post_revisions alter column edited_by drop not null;

comment on column content_post_revisions.edited_by is
  'Кто правил. NULL — правка вне приложения (SQL Editor, скрипт, серверный код), '
  'где нет auth.uid(). Это не «неизвестно, кто из оргкомитета», а «правка сделана '
  'не человеком через интерфейс». Раньше поле было not null, и такие правки не '
  'логировались, а отменялись целиком — см. БАГ 3 в шапке миграции 27.';

-- ---------- БАГ 1: разносим триггер на BEFORE и AFTER ----------

-- Старый совмещённый триггер убираем. Имя освобождается: новый (AFTER) займёт его
-- же, чтобы в схеме не осталось двух похожих имён на одну обязанность.
drop trigger if exists trg_content_post_revision on content_posts;

-- BEFORE — только updated_at. На INSERT не нужен: у колонки есть default now().
create trigger trg_content_posts_updated_at
  before update on content_posts
  for each row
  execute function set_updated_at();

-- AFTER — запись ревизии. Здесь строка уже в таблице, поэтому FK на пост
-- выполняется. Тело функции меняется ещё и потому, что в AFTER-триггере
-- присваивание new.updated_at бесполезно: строка уже записана, и правка не
-- сохранится. Именно поэтому строка new.updated_at = now() отсюда убрана, а не
-- оставлена «на всякий случай» — она создавала бы впечатление, что что-то делает.
create or replace function log_content_post_revision()
returns trigger
language plpgsql
security definer
as $$
declare
  v_editor uuid;
begin
  if tg_op = 'INSERT' then
    v_editor := new.created_by;
  else
    v_editor := auth.uid();
  end if;

  if (tg_op = 'INSERT') or (new.body is distinct from old.body) or (new.title is distinct from old.title) then
    insert into content_post_revisions (post_id, body, title, edited_by)
    values (new.id, new.body, new.title, v_editor);
  end if;

  -- AFTER-триггер: возвращаемое значение игнорируется, но plpgsql требует его.
  return null;
end;
$$;

-- security definer оставлен как был: на content_post_revisions политика разрешает
-- только чтение (04_...), вставку должен делать триггер, а не клиент.
create trigger trg_content_post_revision
  after insert or update on content_posts
  for each row
  execute function log_content_post_revision();
