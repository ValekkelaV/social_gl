-- ============================================================
-- Вайтлист: желаемое отображаемое имя
-- ============================================================
-- Позволяет владельцу задать человеку "нормальное" full_name ещё до его
-- первого входа, вместо имени, которое подставится из Telegram
-- (first_name/last_name, у части людей — на латинице/нике). Если задано —
-- используется при создании people (только на INSERT в вебхуке, т.е. при
-- первом логине этого telegram_id); при повторных входах уже существующего
-- people full_name не перезаписывается автоматически.

alter table whitelisted_usernames
  add column preferred_full_name text;

comment on column whitelisted_usernames.preferred_full_name is
  'Опционально: имя, которое подставится в people.full_name при первом входе '
  'этого username, вместо автоматического значения из Telegram '
  '(first_name + last_name). Не влияет на уже существующих people.';
