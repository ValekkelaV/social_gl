-- ============================================================
-- Вайтлист: необязательное отображаемое имя
-- ============================================================
-- По умолчанию people.full_name при первом входе берётся из Telegram
-- (first_name + last_name из профиля бота), что не всегда совпадает с тем,
-- как человека нужно называть в админке (может быть латиницей, никнеймом
-- и т.д.). Позволяем владельцу задать нормальное имя заранее, в момент
-- добавления в вайтлист — вебхук использует его вместо телеграмного имени,
-- если оно задано.

alter table whitelisted_usernames
  add column display_name text;

comment on column whitelisted_usernames.display_name is
  'Необязательное имя, которое нужно использовать как people.full_name при '
  'первом входе этого username, вместо имени из профиля Telegram. Если не '
  'задано — используется first_name+last_name из Telegram (или сам username, '
  'если оба пусты), как и раньше. НЕ влияет на уже существующих people — '
  'переименование задним числом делается отдельным UPDATE people (см. '
  'admin-экран "Комитеты" -> "Переименовать участника" во фронтенде).';
